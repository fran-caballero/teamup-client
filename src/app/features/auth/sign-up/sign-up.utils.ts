export const generateRandomUser = (): string => {
  const randomAdjectiveIndex = Math.floor(
    Math.random() * adjectives.length - 1,
  );
  const randomAnimalIndex = Math.floor(Math.random() * animals.length - 1);
  const adjective = adjectives[randomAdjectiveIndex];
  let animal = animals[randomAnimalIndex];

  animal = animal.replace(' ', '');

  return adjective + animal;
};

export const generateRandomPassword = (): string => {
  const randomPassword = generatePassword.generate({
    length: 12,
    numbers: true,
    symbols: true,
    lowercase: true,
    uppercase: true,
  });

  return randomPassword;
};
